import assert from 'node:assert';
import fs from 'node:fs';
import { Document, Paragraph, TextRun, Packer } from 'docx';
import { PDFDocument, degrees } from 'pdf-lib';
import QRCode from 'qrcode';
import JSZip from 'jszip';
import { tools, getLocalizedTool, getToolBySlug } from '../src/registry/tool-registry.js';
import { matchToolQuery, calculateToolScore } from '../src/lib/search/toolSearch.js';

console.log('[test-functional] Starting automated functional test suite for Ahadex Tools...\n');

let passedTests = 0;

// Test 1: DOCX Generation (used by pdf-to-word)
console.log('1. Testing DOCX generation engine (pdf-to-word)...');
const doc = new Document({
  sections: [
    {
      children: [
        new Paragraph({
          children: [
            new TextRun({ text: 'Ahadex Tools Functional Test', bold: true }),
            new TextRun({ text: '\nExtracted text from test PDF' }),
          ],
        }),
      ],
    },
  ],
});
const docxBuffer = await Packer.toBuffer(doc);
assert(docxBuffer.length > 500, 'DOCX buffer should be non-empty valid binary');
console.log(`   ✓ DOCX generation succeeded (${docxBuffer.length} bytes produced)`);
passedTests++;

// Test 2: PDF Creation, Rotation, Extraction & Saving (pdf-lib engine)
console.log('2. Testing PDF manipulation engine (split-pdf, pdf-rotate, pdf-page-extractor, merge-pdf)...');
const samplePdf = await PDFDocument.create();
const p1 = samplePdf.addPage([600, 400]);
p1.drawText('Page 1 Content');
const p2 = samplePdf.addPage([600, 400]);
p2.drawText('Page 2 Content');
p2.setRotation(degrees(90));

const sampleBytes = await samplePdf.save();
assert(sampleBytes.length > 0, 'PDF bytes should be non-empty');
assert(
  String.fromCharCode(sampleBytes[0], sampleBytes[1], sampleBytes[2], sampleBytes[3], sampleBytes[4]) === '%PDF-',
  'PDF header signature must start with %PDF-'
);

// Test copying page (page extractor / split)
const extractedPdf = await PDFDocument.create();
const copied = await extractedPdf.copyPages(samplePdf, [0]);
extractedPdf.addPage(copied[0]);
const extractedBytes = await extractedPdf.save();
assert(extractedBytes.length > 0, 'Extracted page PDF should be valid');
console.log(`   ✓ PDF engine (creation, page extraction, rotation, serialization) passed (${sampleBytes.length} bytes)`);
passedTests++;

// Test 3: QR Code Engine (photo-qr-code)
console.log('3. Testing QR Code generator engine (photo-qr-code)...');
const qrDataUrl = await QRCode.toDataURL('https://ahadex.online/tool/photo-qr-code', {
  errorCorrectionLevel: 'H',
  margin: 1,
});
assert(qrDataUrl.startsWith('data:image/png;base64,'), 'QR data URL should be a valid PNG base64 string');
console.log(`   ✓ QR Code generator passed (High Error Correction level H)`);
passedTests++;

// Test 4: ZIP Packaging Engine (split-pdf multiple pages download)
console.log('4. Testing ZIP archive engine (split-pdf individual pages)...');
const zip = new JSZip();
zip.file('page-1.pdf', extractedBytes);
zip.file('info.txt', 'Generated by Ahadex Tools');
const zipBlob = await zip.generateAsync({ type: 'nodebuffer' });
assert(zipBlob.length > 100, 'ZIP archive should be valid');
console.log(`   ✓ ZIP packaging engine passed (${zipBlob.length} bytes)`);
passedTests++;

// Test 5: PDF Structural Stream Clean-up (compress-pdf stream mode)
console.log('5. Testing PDF Structural Stream Clean-up engine (compress-pdf stream mode)...');
const optPdf = await PDFDocument.load(sampleBytes);
optPdf.setTitle('');
optPdf.setAuthor('');
optPdf.setProducer('Ahadex Tools In-Browser Optimizer');
const optBytes = await optPdf.save({ useObjectStreams: true });
assert(optBytes.length > 0, 'Optimized PDF bytes should be valid non-empty');
assert(
  String.fromCharCode(optBytes[0], optBytes[1], optBytes[2], optBytes[3], optBytes[4]) === '%PDF-',
  'Optimized PDF header signature must be valid'
);
// Integrity re-opening check
const reloaded = await PDFDocument.load(optBytes);
assert(reloaded.getPageCount() === 2, 'Verified reloaded PDF must have 2 pages');
console.log(`   ✓ PDF stream clean-up & integrity verification passed (${optBytes.length} bytes produced)`);
passedTests++;

// Test 6: Multilingual Search Accuracy (English & Bengali)
console.log('6. Testing Multilingual Search Engine accuracy across all 24 tools...');
const searchTestCases = [
  { query: 'PDF to Word', expectedSlug: 'pdf-to-word' },
  { query: 'পিডিএফ থেকে ওয়ার্ড', expectedSlug: 'pdf-to-word' },
  { query: 'পিডিএফ ওয়ার্ডে রূপান্তর', expectedSlug: 'pdf-to-word' },
  { query: 'ছবি ছোট করুন', expectedSlug: 'image-compressor' },
  { query: 'ছবির সাইজ কমান', expectedSlug: 'image-compressor' },
  { query: 'ছবি দিয়ে পিডিএফ', expectedSlug: 'image-to-pdf' },
  { query: 'ছবি থেকে লেখা', expectedSlug: 'image-to-text' },
  { query: 'ব্যাকগ্রাউন্ড রিমুভ', expectedSlug: 'background-remover' },
  { query: 'পাসওয়ার্ড জেনারেটর', expectedSlug: 'password-generator' },
  { query: 'পিডিএফ মার্জ', expectedSlug: 'merge-pdf' },
  { query: 'JSON Formatter', expectedSlug: 'json-formatter' },
  { query: 'heic to jpg', expectedSlug: 'heic-to-jpg' },
  { query: 'word count', expectedSlug: 'word-counter' },
  { query: 'color picker', expectedSlug: 'color-picker' },
];

const localizedTools = tools.map((t) => getLocalizedTool(t, 'bn'));

for (const testCase of searchTestCases) {
  const ranked = localizedTools
    .map((t) => {
      const raw = tools.find((r) => r.id === t.id);
      return { tool: t, score: calculateToolScore(t, testCase.query, raw) };
    })
    .filter((m) => m.score > 0)
    .sort((a, b) => b.score - a.score);

  assert(ranked.length > 0, `Query "${testCase.query}" should return results`);
  const topMatch = ranked[0].tool.slug;
  assert(
    topMatch === testCase.expectedSlug,
    `Query "${testCase.query}" expected top match "${testCase.expectedSlug}", got "${topMatch}"`
  );
  console.log(`   ✓ Search "${testCase.query}" -> ${topMatch} (Score: ${ranked[0].score})`);
}
passedTests++;

console.log(`\n7. Testing SEO Indexing & Slug Resolution Integrity across all 24 tools...`);
for (const tool of tools) {
  // Test slug resolution resilience
  assert(getToolBySlug(tool.slug), `Slug "${tool.slug}" must resolve`);
  assert(getToolBySlug(`${tool.slug}/`), `Slug with trailing slash "${tool.slug}/" must resolve`);
  assert(getToolBySlug(`${tool.slug}.html`), `Slug with .html "${tool.slug}.html" must resolve`);
  assert(getToolBySlug(tool.slug.toUpperCase()), `Uppercase slug "${tool.slug.toUpperCase()}" must resolve`);

  // Test SEO canonical & metadata
  assert(tool.seo.canonical.startsWith('/tool/'), `Canonical path for ${tool.slug} must start with /tool/`);
  assert(tool.seo.title.length > 10, `SEO title for ${tool.slug} must be meaningful`);
  assert(tool.seo.description.length > 30, `SEO description for ${tool.slug} must be informative`);

  // Test localized BN SEO
  const bn = getLocalizedTool(tool, 'bn');
  assert(bn.seo.title.length > 5, `BN SEO title for ${tool.slug} must exist`);
  assert(bn.seo.description.length > 20, `BN SEO description for ${tool.slug} must exist`);
}
console.log(`   ✓ All 24 tools verified: resilient slug resolution, canonical URLs, and bilingual SEO metadata`);
passedTests++;

console.log(`\n8. Testing Google Analytics, Tag Manager, AdSense & Cloudflare Pages Configuration...`);
const indexHtmlContent = fs.readFileSync('index.html', 'utf8');
const adsTxtContent = fs.readFileSync('public/ads.txt', 'utf8');
const redirectsContent = fs.readFileSync('public/_redirects', 'utf8');

assert(indexHtmlContent.includes('ca-pub-5216241068377334'), 'index.html must include AdSense client ID');
assert(indexHtmlContent.includes('G-SFQG7CCVTQ'), 'index.html must include Google Analytics tag G-SFQG7CCVTQ');
assert(indexHtmlContent.includes('GTM-56SHPW93'), 'index.html must include Google Tag Manager GTM-56SHPW93');
assert(indexHtmlContent.indexOf('GTM-56SHPW93') < indexHtmlContent.indexOf('<title>'), 'GTM script must be at top of head before <title>');
assert(indexHtmlContent.indexOf('ns.html?id=GTM-56SHPW93') > indexHtmlContent.indexOf('<body>'), 'GTM noscript must be immediately after <body>');
assert(adsTxtContent.includes('pub-5216241068377334'), 'ads.txt must include pub-5216241068377334');
assert(redirectsContent.includes('/* /index.html 200'), '_redirects must include Cloudflare Pages SPA rewrite rule');
assert(fs.existsSync('.nvmrc'), '.nvmrc must exist for Cloudflare Pages build environment');

console.log('   ✓ All tracking tags (G-SFQG7CCVTQ, GTM-56SHPW93, ca-pub-5216241068377334) & Cloudflare Pages files verified');
passedTests++;

console.log(`\n🎉 All ${passedTests} automated functional tests passed successfully!\n`);
